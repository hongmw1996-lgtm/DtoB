    {
        var c = new TextDxfGeometryReader(geometryLimits).Read(structure, geometryToken);
        var d = new TextDxfBlockAnnotationReader().Read(c, annotationToken);
        return new TextDxfIdentityGraphReader().Read(d, provenance ? Document() : null, graphToken);
    }
